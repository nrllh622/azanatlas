// büyük İslam âlimleri/bilim insanları/mutasavvıflar, modern Müslüman
// ülkelerin bağımsızlık günleri de dahil edildi — aksi halde 365 güne
// yaklaşmak mümkün değildi. 8. turda kalan ~174 boş gün 6 paralel ajana
